-- Crea las tablas del sistema: cuentas, catálogos, solicitudes y auditoría.

-- Cuentas de la central (admin, operador y usuario interno)
CREATE TABLE IF NOT EXISTS public.usuarios (
    id_usuario       integer GENERATED BY DEFAULT AS IDENTITY,
    nombre           varchar(100) NOT NULL,
    usuario          varchar(50)  NOT NULL,
    correo           varchar(120),
    contrasena       varchar(255) NOT NULL,
    -- admin, operador o sistema
    rol              varchar(30)  NOT NULL,
    -- permite o bloquea el acceso
    activo           boolean      NOT NULL DEFAULT true,
    -- Se incrementa al cerrar sesión o cambiar contraseña para invalidar JWT.
    token_version    integer      NOT NULL DEFAULT 0,
    ultimo_acceso    timestamptz,
    fecha_registro   timestamptz  NOT NULL DEFAULT now(),
    -- UID externo opcional; no se usa en el entorno local.
    external_uid     uuid,
    -- Claves y validaciones: rol permitido, campos obligatorios y correo válido.
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('admin', 'operador', 'sistema')),
    CONSTRAINT ck_usuarios_usuario CHECK (btrim(usuario) <> ''),
    CONSTRAINT ck_usuarios_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_usuarios_correo CHECK (
        correo IS NULL
        OR correo ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    ),
    CONSTRAINT uq_usuarios_external_uid UNIQUE (external_uid)
);

COMMENT ON TABLE public.usuarios IS
  'Cuentas autorizadas de la central. La contraseña se guarda como hash scrypt.';
COMMENT ON COLUMN public.usuarios.external_uid IS
  'UID de autenticación externa asociado opcionalmente; NULL si se usa el JWT de Flask.';

-- Catálogo de tipos de emergencia

CREATE TABLE IF NOT EXISTS public.tipos_emergencia (
    id_tipo       integer GENERATED BY DEFAULT AS IDENTITY,
    nombre        varchar(100) NOT NULL,
    descripcion   varchar(255),
    CONSTRAINT pk_tipos_emergencia PRIMARY KEY (id_tipo),
    CONSTRAINT uq_tipos_emergencia_nombre UNIQUE (nombre),
    CONSTRAINT ck_tipos_emergencia_nombre CHECK (btrim(nombre) <> '')
);

COMMENT ON TABLE public.tipos_emergencia IS
  'Catálogo de tipos de emergencia disponibles en SOSNET.';

-- Dispositivos y formularios web

CREATE TABLE IF NOT EXISTS public.dispositivos (
    id_dispositivo   integer GENERATED BY DEFAULT AS IDENTITY,
    codigo           varchar(50)  NOT NULL,
    nombre           varchar(100) NOT NULL,
    -- web o desconocido
    tipo             varchar(30)  NOT NULL,
    -- activo, inactivo o mantenimiento
    estado           varchar(20)  NOT NULL DEFAULT 'activo',
    fecha_registro   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_dispositivos PRIMARY KEY (id_dispositivo),
    CONSTRAINT uq_dispositivos_codigo UNIQUE (codigo),
    CONSTRAINT ck_dispositivos_codigo CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_dispositivos_tipo CHECK (
        tipo IN ('web', 'desconocido')
    ),
    CONSTRAINT ck_dispositivos_estado CHECK (
        estado IN ('activo', 'inactivo', 'mantenimiento')
    )
);

COMMENT ON TABLE public.dispositivos IS
  'Dispositivos y formularios web que originan solicitudes SOS.';

-- Configuración institucional 

CREATE TABLE IF NOT EXISTS public.configuracion_central (
    id_configuracion integer PRIMARY KEY DEFAULT 1,
    nombre           varchar(100) NOT NULL,
    ubicacion        varchar(150) NOT NULL,
    actualizado_en   timestamptz  NOT NULL DEFAULT now(),
    -- Solo puede existir la fila 1.
    CONSTRAINT ck_configuracion_singleton CHECK (id_configuracion = 1),
    CONSTRAINT ck_configuracion_nombre CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_configuracion_ubicacion CHECK (btrim(ubicacion) <> '')
);

COMMENT ON TABLE public.configuracion_central IS
  'Identificación de la central de operaciones. Solo existe la fila 1.';

-- Solicitudes SOS

CREATE TABLE IF NOT EXISTS public.solicitudes_sos (
    id_solicitud       integer GENERATED BY DEFAULT AS IDENTITY,
    codigo_mensaje     varchar(50)  NOT NULL,
    -- puede quedar vacío
    nombre_solicitante varchar(100),
    id_tipo            integer      NOT NULL,
    id_dispositivo     integer      NOT NULL,
    -- texto libre o coordenadas GPS
    ubicacion          varchar(255) NOT NULL,
    -- entre 1 y 1000 personas
    cantidad_personas  integer      NOT NULL DEFAULT 1,
    descripcion        varchar(500),
    -- alta, media o baja
    prioridad          varchar(20)  NOT NULL DEFAULT 'media',
    -- pending (pendiente), in_progress (en proceso) o resolved (resuelta)
    estado             varchar(30)  NOT NULL DEFAULT 'pending',
    fecha_recepcion    timestamptz  NOT NULL DEFAULT now(),
    actualizado_en     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_solicitudes_sos PRIMARY KEY (id_solicitud),
    CONSTRAINT uq_solicitudes_sos_codigo UNIQUE (codigo_mensaje),
    CONSTRAINT ck_solicitudes_sos_codigo CHECK (btrim(codigo_mensaje) <> ''),
    CONSTRAINT ck_solicitudes_sos_ubicacion CHECK (btrim(ubicacion) <> ''),
    CONSTRAINT ck_solicitudes_sos_personas CHECK (cantidad_personas BETWEEN 1 AND 1000),
    CONSTRAINT ck_solicitudes_sos_prioridad CHECK (prioridad IN ('alta', 'media', 'baja')),
    CONSTRAINT ck_solicitudes_sos_estado CHECK (estado IN ('pending', 'in_progress', 'resolved')),
    -- Cada solicitud pertenece a un tipo de emergencia y a un dispositivo.
    CONSTRAINT fk_solicitudes_sos_tipo
        FOREIGN KEY (id_tipo) REFERENCES public.tipos_emergencia (id_tipo)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_solicitudes_sos_dispositivo
        FOREIGN KEY (id_dispositivo) REFERENCES public.dispositivos (id_dispositivo)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

COMMENT ON TABLE public.solicitudes_sos IS
  'Solicitudes de emergencia recibidas desde el formulario web.';
COMMENT ON COLUMN public.solicitudes_sos.estado IS
  'pending = pendiente, in_progress = en proceso, resolved = resuelta.';

-- Registros de comunicación 

CREATE TABLE IF NOT EXISTS public.registros_comunicacion (
    id_registro       integer GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud      integer      NOT NULL,
    fecha_recepcion   timestamptz  NOT NULL DEFAULT now(),
    -- recibido, duplicado o error
    estado_recepcion  varchar(30)  NOT NULL DEFAULT 'recibido',
    id_dispositivo    integer      NOT NULL,
    CONSTRAINT pk_registros_comunicacion PRIMARY KEY (id_registro),
    CONSTRAINT ck_registros_estado CHECK (
        estado_recepcion IN ('recibido', 'duplicado', 'error')
    ),
    -- Si se borra la solicitud, sus comunicaciones también se borran.
    CONSTRAINT fk_registros_solicitud
        FOREIGN KEY (id_solicitud) REFERENCES public.solicitudes_sos (id_solicitud)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_registros_dispositivo
        FOREIGN KEY (id_dispositivo) REFERENCES public.dispositivos (id_dispositivo)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

COMMENT ON TABLE public.registros_comunicacion IS
  'Cada recepción de un mensaje SOS; hoy se registra una por solicitud.';

-- Auditoría: historial de estados

CREATE TABLE IF NOT EXISTS auditoria.historial_estados (
    id_historial      integer GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud      integer      NOT NULL,
    -- usuario que hizo el cambio
    id_usuario        integer      NOT NULL,
    estado_anterior   varchar(30),
    estado_nuevo      varchar(30)  NOT NULL,
    fecha_cambio      timestamptz  NOT NULL DEFAULT now(),
    observacion       varchar(255),
    CONSTRAINT pk_historial_estados PRIMARY KEY (id_historial),
    CONSTRAINT ck_historial_estado_nuevo CHECK (
        estado_nuevo IN ('pending', 'in_progress', 'resolved')
    ),
    CONSTRAINT ck_historial_estado_anterior CHECK (
        estado_anterior IS NULL
        OR estado_anterior IN ('pending', 'in_progress', 'resolved')
    ),
    -- Si se borra la solicitud, su historial también se borra.
    CONSTRAINT fk_historial_solicitud
        FOREIGN KEY (id_solicitud) REFERENCES public.solicitudes_sos (id_solicitud)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_historial_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuarios (id_usuario)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

COMMENT ON TABLE auditoria.historial_estados IS
  'Historial inmutable de cambios de estado, generado por trigger.';

-- Auditoría: actividad de usuarios y del sistema

CREATE TABLE IF NOT EXISTS auditoria.actividad (
    id_actividad   integer GENERATED BY DEFAULT AS IDENTITY,
    -- puede quedar vacío en acciones del sistema
    id_usuario     integer,
    accion         varchar(50)  NOT NULL,
    descripcion    varchar(255) NOT NULL,
    entidad        varchar(40),
    entidad_id     integer,
    fecha          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_actividad PRIMARY KEY (id_actividad),
    CONSTRAINT ck_actividad_accion CHECK (btrim(accion) <> ''),
    CONSTRAINT ck_actividad_descripcion CHECK (btrim(descripcion) <> ''),
    -- Si se borra el usuario, la actividad se conserva sin actor.
    CONSTRAINT fk_actividad_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuarios (id_usuario)
        ON DELETE SET NULL ON UPDATE CASCADE
);

COMMENT ON TABLE auditoria.actividad IS
  'Auditoría de accesos, administración y cambios operativos.';
